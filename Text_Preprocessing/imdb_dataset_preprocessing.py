import numpy as np
import pandas as pd

df = pd.read_csv('/content/IMDB Dataset.csv')
print("Dataframe Loaded")
print(df.info())

df['review'] = df['review'].str.lower()

import string

def remove_punctuation(text):
    result = ""
    for char in text:
        if char not in string.punctuation:
            result += char
    return result

df['review'] = df['review'].apply(lambda text: remove_punctuation(text))
print(df['review'][0])

from textblob import TextBlob
def correct_spelling(text):
    return str(TextBlob(text).correct())

import nltk
nltk.download('stopwords')
from nltk.corpus import stopwords
stpw = stopwords.words('english')
print(stpw)

def remove_stpw(text):
    new_text = []
    for word in text.split():
        if word in stpw:
            continue
        new_text.append(word)
    return " ".join(new_text)

df['review'] = df['review'].apply(lambda text: remove_stpw(text))
print("Stopword Removed")
print(df['review'][0])

from nltk.tokenize import word_tokenize
nltk.download('punkt')
nltk.download('punkt_tab')

df['review'] = df['review'].apply(lambda text: word_tokenize(text))
print("Tokenization done")
print(df['review'][0])

import nltk
from nltk.stem import WordNetLemmatizer
nltk.download('wordnet')
nltk.download('omw-1.4')

def lemitize(tokenize_text_list):
  ntl = []
  Lemitizer =WordNetLemmatizer()
  for word in tokenize_text_list:
    ntl.append(Lemitizer.lemmatize(word, pos='v'))
  return ntl

df['review'] = df['review'].apply(lambda text: lemitize(text))
print("Lemmatization done")
print(df['review'][0])

def remove_br_html(text_list):
  new_text=[]
  for word in text_list:
    if word == 'br':
      continue
    new_text.append(word)
  return new_text

df['review'] = df['review'].apply(lambda text: remove_br_html(text))
print("HTML Removed")
print(df['review'][0])

df.to_csv('imdb_text_preprocessed.csv', index = False)